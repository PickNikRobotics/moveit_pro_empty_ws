#!/usr/bin/env python3
"""Generate the Ranger Mini's MuJoCo model and the suite_106 walls.

    python3 generate_mjcf.py            # writes mjcf/ in this package's source tree
    python3 generate_mjcf.py --check    # exits 1 if the committed files are stale

Writes two files, both marked GENERATED:

  mjcf/agilex_ranger_mini.xml   the robot, read from the mock config's expanded URDF
  mjcf/suite_106_walls.xml      the walls, read from the mock config's suite_106 map

So the simulated robot cannot drift from the URDF, and the walls the lidar sees
are the walls AMCL matches. The MJCF world frame is the map frame.

Needs xacro, numpy and Pillow, and the agilex_ranger_mini_mock package on the
ament index (source the workspace first).
"""

import argparse
import math
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np
import xacro
import yaml
from ament_index_python.packages import get_package_share_directory

PLANAR_JOINTS = ("linear_x_joint", "linear_y_joint", "rotational_yaw_joint")
CORNERS = ("fl", "fr", "rl", "rr")

# Planar actuator gains, N per m/s and N m per rad/s; docs/AGENT_COMMENTS.md.
LINEAR_KV = 2000.0
YAW_KV = 500.0
# Holds the unactuated steering modules straight while the base turns.
STEERING_STIFFNESS = 50.0
STEERING_DAMPING = 5.0
WHEEL_DAMPING = 1.0
RAIL_MASS = 1.0

# The simulated lidar: name prefix of the beam sites, beam count, noise and range.
LIDAR_NAME = "sim_lidar"
LIDAR_BEAMS = 180
LIDAR_NOISE_STD = 0.01
LIDAR_RANGE = (0.05, 10.0)

WALL_HEIGHT = 2.5
WALL_RGBA = "0.72 0.73 0.75 1"
BODY_RGBA = "0.20 0.22 0.25 1"
WHEEL_RGBA = "0.08 0.08 0.09 1"


def fmt(*values):
    return " ".join(f"{v:.9g}" for v in values)


def expand_urdf():
    """Expand the mock config's URDF with its own defaults."""
    mock = Path(get_package_share_directory("agilex_ranger_mini_mock"))
    doc = xacro.process_file(str(mock / "description/agilex_ranger_mini.urdf.xacro"))
    return ET.fromstring(doc.toxml()), mock


def joint(urdf, name):
    return next(j for j in urdf.findall("joint") if j.get("name") == name)


def link(urdf, name):
    return next(lk for lk in urdf.findall("link") if lk.get("name") == name)


def xyz(element, attribute="xyz"):
    return [float(v) for v in element.get(attribute, "0 0 0").split()]


def inertial(urdf, name, offset):
    """Return an MJCF <inertial> for a URDF link, shifted by `offset` metres."""
    node = link(urdf, name).find("inertial")
    pos = np.add(xyz(node.find("origin")), offset)
    i = node.find("inertia")
    diag = [float(i.get(k)) for k in ("ixx", "iyy", "izz")]
    mass = float(node.find("mass").get("value"))
    return (
        f'<inertial pos="{fmt(*pos)}" mass="{mass:.9g}" diaginertia="{fmt(*diag)}" />'
    )


def beam_quat(angle):
    """Orientation of a beam site: its +Z, the ray, along `angle` in the XY plane."""
    half = 0.5 * angle
    c = math.sqrt(0.5)
    return (
        c * math.cos(half),
        -c * math.sin(half),
        c * math.cos(half),
        c * math.sin(half),
    )


def render_robot(urdf):
    chassis_z = xyz(joint(urdf, "base_link_to_chassis").find("origin"))[2]
    laser = np.add(
        xyz(joint(urdf, "laser_joint").find("origin")), [0.0, 0.0, chassis_z]
    )
    lines = [
        "<!-- GENERATED by scripts/generate_mjcf.py from the mock config's URDF. Do not edit. -->",
        "<mujocoinclude>",
        "  <worldbody>",
        '    <body name="virtual_rail_link_1">',
        f'      <inertial pos="0 0 0" mass="{RAIL_MASS}" diaginertia="0.001 0.001 0.001" />',
        '      <joint name="linear_x_joint" type="slide" axis="1 0 0" />',
        '      <body name="virtual_rail_link_2">',
        f'        <inertial pos="0 0 0" mass="{RAIL_MASS}" diaginertia="0.001 0.001 0.001" />',
        '        <joint name="linear_y_joint" type="slide" axis="0 1 0" />',
        '        <body name="base_link">',
        "          " + inertial(urdf, "chassis_link", [0.0, 0.0, chassis_z]),
        '          <joint name="rotational_yaw_joint" type="hinge" axis="0 0 1" />',
    ]
    for index, collision in enumerate(link(urdf, "chassis_link").findall("collision")):
        pos = np.add(xyz(collision.find("origin")), [0.0, 0.0, chassis_z])
        half = 0.5 * np.array(xyz(collision.find("geometry/box"), "size"))
        lines.append(
            f'          <geom name="chassis_collision_{index}" type="box" pos="{fmt(*pos)}"'
            f' size="{fmt(*half)}" rgba="{BODY_RGBA}" />'
        )
    radius = float(
        link(urdf, "laser_link").find("visual/geometry/cylinder").get("radius")
    )
    length = float(
        link(urdf, "laser_link").find("visual/geometry/cylinder").get("length")
    )
    lines.append(
        f'          <geom name="laser_visual" type="cylinder" pos="{fmt(*laser)}"'
        f' size="{fmt(radius, 0.5 * length)}" contype="0" conaffinity="0" rgba="{WHEEL_RGBA}" />'
    )

    for corner in CORNERS:
        steer = joint(urdf, f"{corner}_steering_joint")
        pivot = np.add(xyz(steer.find("origin")), [0.0, 0.0, chassis_z])
        limit = steer.find("limit")
        wheel_drop = xyz(joint(urdf, f"{corner}_wheel_joint").find("origin"))
        wheel = link(urdf, f"{corner}_wheel_link").find("collision/geometry/cylinder")
        lines += [
            f'          <body name="{corner}_steering_link" pos="{fmt(*pivot)}">',
            "            " + inertial(urdf, f"{corner}_steering_link", [0, 0, 0]),
            f'            <joint name="{corner}_steering_joint" type="hinge" axis="0 0 1"'
            f' range="{limit.get("lower")} {limit.get("upper")}"'
            f' stiffness="{STEERING_STIFFNESS}" damping="{STEERING_DAMPING}" />',
            f'            <body name="{corner}_wheel_link" pos="{fmt(*wheel_drop)}">',
            "              " + inertial(urdf, f"{corner}_wheel_link", [0, 0, 0]),
            f'              <joint name="{corner}_wheel_joint" type="hinge" axis="0 1 0"'
            f' damping="{WHEEL_DAMPING}" />',
            f'              <geom name="{corner}_wheel_visual" type="cylinder"'
            f' size="{fmt(float(wheel.get("radius")), 0.5 * float(wheel.get("length")))}"'
            ' quat="0.707106781 0.707106781 0 0"'
            f' contype="0" conaffinity="0" rgba="{WHEEL_RGBA}" />',
            "            </body>",
            "          </body>",
        ]

    increment = 2.0 * math.pi / LIDAR_BEAMS
    for beam in range(LIDAR_BEAMS):
        lines.append(
            f'          <site name="{LIDAR_NAME}-{beam:03d}" pos="{fmt(*laser)}"'
            f' quat="{fmt(*beam_quat(beam * increment))}" size="0.005" rgba="0 0 0 0" />'
        )
    lines += ["        </body>", "      </body>", "    </body>", "  </worldbody>"]

    # user: noise std, angle min, angle max, angle increment, range min, range max.
    user = fmt(
        LIDAR_NOISE_STD, 0.0, (LIDAR_BEAMS - 1) * increment, increment, *LIDAR_RANGE
    )
    lines.append("  <sensor>")
    for beam in range(LIDAR_BEAMS):
        lines.append(
            f'    <rangefinder site="{LIDAR_NAME}-{beam:03d}" user="{user}" />'
        )
    lines.append("  </sensor>")

    lines.append("  <actuator>")
    for name in PLANAR_JOINTS:
        limit = joint(urdf, name).find("limit")
        top = float(limit.get("velocity"))
        kv = YAW_KV if name == "rotational_yaw_joint" else LINEAR_KV
        lines.append(
            f'    <velocity name="{name}" joint="{name}" kv="{kv:g}" ctrlrange="{fmt(-top, top)}" />'
        )
    lines += ["  </actuator>", "</mujocoinclude>", ""]
    return "\n".join(lines)


def merge_rectangles(occupied):
    """Cover every occupied cell with disjoint axis-aligned rectangles, greedily in scan order."""
    remaining = occupied.copy()
    rows, cols = remaining.shape
    rectangles = []
    for row in range(rows):
        col = 0
        while col < cols:
            if not remaining[row, col]:
                col += 1
                continue
            width = 1
            while col + width < cols and remaining[row, col + width]:
                width += 1
            height = 1
            while (
                row + height < rows and remaining[row + height, col : col + width].all()
            ):
                height += 1
            remaining[row : row + height, col : col + width] = False
            rectangles.append((row, col, height, width))
            col += width
    return rectangles


def render_walls(map_yaml):
    from PIL import Image

    meta = yaml.safe_load(map_yaml.read_text())
    origin = meta["origin"]
    if len(origin) > 2 and abs(float(origin[2])) > 1e-9:
        raise SystemExit(f"{map_yaml}: a rotated map origin is not supported.")
    grey = np.array(Image.open(map_yaml.parent / meta["image"]).convert("L"))
    if meta.get("negate", 0):
        grey = 255 - grey
    # map_server's rule: occupancy is (255 - grey) / 255, occupied above occupied_thresh.
    occupied = (255.0 - grey) / 255.0 > float(meta["occupied_thresh"])
    res = float(meta["resolution"])
    rows = occupied.shape[0]

    lines = [
        f"<!-- GENERATED by scripts/generate_mjcf.py from {map_yaml.name}. Do not edit. -->",
        "<mujocoinclude>",
        "  <worldbody>",
    ]
    rectangles = merge_rectangles(occupied)
    assert sum(h * w for _, _, h, w in rectangles) == int(occupied.sum())
    for index, (row, col, height, width) in enumerate(rectangles):
        # Image row 0 is the top of the map, while map y grows upwards.
        x0 = origin[0] + col * res
        y1 = origin[1] + (rows - row) * res
        lines.append(
            f'    <geom name="wall_{index:04d}" type="box"'
            f' pos="{fmt(x0 + 0.5 * width * res, y1 - 0.5 * height * res, 0.5 * WALL_HEIGHT)}"'
            f' size="{fmt(0.5 * width * res, 0.5 * height * res, 0.5 * WALL_HEIGHT)}"'
            f' rgba="{WALL_RGBA}" />'
        )
    lines += ["  </worldbody>", "</mujocoinclude>", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="Fail if the files are stale."
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "mjcf",
        help="Directory to write into.",
    )
    args = parser.parse_args()

    urdf, mock = expand_urdf()
    outputs = {
        "agilex_ranger_mini.xml": render_robot(urdf),
        "suite_106_walls.xml": render_walls(mock / "maps/suite_106.yaml"),
    }
    stale = []
    for name, text in outputs.items():
        path = args.out / name
        if args.check:
            if not path.is_file() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
            print(f"wrote {path}")
    if stale:
        print(f"stale, re-run generate_mjcf.py: {', '.join(stale)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
